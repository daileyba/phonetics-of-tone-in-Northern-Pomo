def z_score_normalize_f0(df, group_by, num_of_measurements):
    """
    Z-score normalize F0 columns by speaker using all F0 values per speaker,
    preserving NaN values for time alignment
    """
    z_scored_df = df.copy()

    f0_columns = [f'F0_{i}' for i in range(num_of_measurements)]

    # DETAILED VERSION: Calculate speaker statistics from ALL F0 measurements
    group_stats = {}

    for group in z_scored_df[group_by].unique():
        group_df = z_scored_df[z_scored_df[group_by] == group]

        # Collect all valid F0 values for this speaker across all F0 columns
        all_f0_values = []
        for col in f0_columns:
            if col in group_df.columns:
                valid_values = group_df[col].dropna()  # Remove NaN for stats calculation
                valid_values = valid_values[valid_values > 0]  # Remove 0 or negative F0
                all_f0_values.extend(valid_values.tolist())

        if len(all_f0_values) > 1:
            group_stats[group] = {
                'mean': np.mean(all_f0_values),
                'std': np.std(all_f0_values),
                'n_measurements': len(all_f0_values)
            }
            print(f"Group {group}: mean={group_stats[group]['mean']:.1f}Hz, "
                  f"std={group_stats[group]['std']:.1f}Hz, "
                  f"n={group_stats[group]['n_measurements']}")

    # Apply normalization to each F0 column, keeping NaN values as NaN
    for col in f0_columns:
        if col in z_scored_df.columns:
            normalized_col = f'{col}_ZSCORE'

            # Initialize with NaN (preserves original NaN pattern)
            z_scored_df[normalized_col] = np.nan

            for group in group_stats.keys():
                if group_stats[group]['std'] > 0:
                    # Create mask for valid values for this speaker
                    group_mask = z_scored_df[group_by] == group
                    valid_mask = z_scored_df[col].notna() & (z_scored_df[col] > 0)  # Not NaN and > 0
                    mask = group_mask & valid_mask

                    # Apply z-score normalization using speaker's overall stats
                    z_scored_df.loc[mask, normalized_col] = (
                        (z_scored_df.loc[mask, col] - group_stats[group]['mean']) /
                        group_stats[group]['std']
                    )
                    # NaN values remain NaN automatically

    return z_scored_df, group_stats



def clean_f0_from_non_sonorant_consonants(df, non_sonorant_consonants=None, num_of_measurements=20):
  if non_sonorant_consonants == None:
    non_sonorant_consonants = ["b", "p", "ph", "p'", "d", "t", "th", "t'", "T", "Th", "T'", "k", "kh", "k'"
                           "ts", "ts'", "j", "ch", "ch'", "s", "s'", "sh", "x",
                           "?", "h"]

  clean_df = df.copy()

  clean_df.loc[clean_df["SEG_ID"].str.split("[_+]", regex=True).str[0].isin(non_sonorant_consonants), ["F0_0", "F0_1", "F0_2", "F0_3", "F0_4", "F0_5",
                                                                                "F0_6", "F0_7", "F0_8"]] = np.nan

  # Create a mask for rows where previous segment is non-sonorant
  prev_non_sonorant_mask = clean_df["PREV_SEG_ID"].str.split("_+", regex=True).str[0].isin(non_sonorant_consonants)

  # For each F0 measurement point, check if it's within 10ms of the previous segment end
  for i in range(num_of_measurements):  # F0_0 through F0_8
      f0_col = f"F0_{i}"
      midpoint_col = f"F0_MIDPOINT_{i}"

      # Calculate distance from F0 timepoint to previous segment end (in ms)
      time_distance = clean_df[midpoint_col] - clean_df["SEG_START"]

      # Set to NaN if: (1) previous segment is non-sonorant AND (2) within 10ms
      within_10ms = time_distance <= 0.01

      clean_df.loc[prev_non_sonorant_mask & within_10ms, f0_col] = np.nan


  # Create a mask for rows where previous segment is non-sonorant
  next_non_sonorant_mask = clean_df["NEXT_SEG_ID"].str.split("_+", regex=True).str[0].isin(non_sonorant_consonants)

  # For each F0 measurement point, check if it's within 10ms of the previous segment end
  for i in range(num_of_measurements):  # F0_0 through F0_num_of_measurements-1
      f0_col = f"F0_{i}"
      midpoint_col = f"F0_MIDPOINT_{i}"

      # Calculate distance from F0 timepoint to previous segment end (in ms)
      time_distance = clean_df["SEG_END"] - clean_df[midpoint_col]

      # Set to NaN if: (1) previous segment is non-sonorant AND (2) within 10ms
      within_10ms = time_distance <= 0.01

      clean_df.loc[next_non_sonorant_mask & within_10ms, f0_col] = np.nan
  return clean_df

