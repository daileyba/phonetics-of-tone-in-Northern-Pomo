#Add tone info
def add_tone_info(df):

  def assign_tone_by_word(group):
      """Process all syllables in a word and assign tones."""
      # Get unique syllables in order (assuming segments are already ordered)
      syllables = group.drop_duplicates(subset=['FILE_ID', 'SYLL_ID', 'SYLL_NUM_IN_WORD']).sort_values('SYLL_NUM_IN_WORD')

      tones = []
      h_assigned = False

      for idx, row in syllables.iterrows():
          structure = row['SYLL_ID']

          # Rule 1: ':' gets L
          if ':' in structure and structure.lower() != "cv:":
              tones.append('L')
              h_assigned = True

          # Rule 2: 'vv' without ':' gets H
          elif 'vv' in structure.lower() and ':' not in structure:
              tones.append('H')
              h_assigned = True

          # Rule 3: CVC gets H only if no prior heavy syllable
          elif structure.lower() == 'cvc':
              if not h_assigned:
                  tones.append('H')
                  h_assigned = True
              else:
                  tones.append('N')

          # Rule 4: everything else gets N
          else:
              tones.append('N')

      # Create word tone structure string
      word_tone_structure = '.'.join(tones)

      # Map tones back to all segments in the word
      # Create a mapping from syllable position to tone
      syll_to_tone = dict(zip(syllables['SYLL_NUM_IN_WORD'], tones))

      # Assign tone to each segment based on its syllable position
      group['TONE'] = group['SYLL_NUM_IN_WORD'].map(syll_to_tone)
      group['WORD_TONE_STRUCTURE'] = word_tone_structure

      return group

  # Apply to each word
  result_df = (
      df.groupby(['FILE_ID', 'WORD_ID', 'WORD_START', 'WORD_END'], sort=False, group_keys=False)
      .apply(assign_tone_by_word)
  )

  return result_df



def get_word_tone_category(word_tone_structure, num_syllables): #change name to add_word_tone_category
    """
    Extract single tone category from word tone structure.
    Returns 'H' if word has H, 'L' if word has L.
    For all-N words: returns 'H' if >1 syllable, 'N' if 1 syllable.
    """
    if pd.isna(word_tone_structure):
        return None

    if 'H' in word_tone_structure:
        return 'H'
    elif 'L' in word_tone_structure:
        return 'L'
    else:  # All N's
        # Multi-syllable N-only words -> H
        # Single-syllable N-only words -> N
        #return 'H' if num_syllables > 1 else 'N'
        return 'N'

def add_neighboring_tones(df, full=True):
  # Get one row per word with FILE_ID
  word_tones = df.groupby(['FILE_ID', 'WORD_START', 'WORD_END']).agg({
      'WORD_TONE_STRUCTURE': 'first',
      'NUM_OF_SYLLS_IN_WORD': 'first'  # Need this to count syllables
  }).reset_index().sort_values(['FILE_ID', 'WORD_START'])

  # Apply tone category function with number of syllables
  word_tones['WORD_TONE_CAT'] = word_tones.apply(
      lambda row: get_word_tone_category(row['WORD_TONE_STRUCTURE'], row['NUM_OF_SYLLS_IN_WORD']),
      axis=1
  )

  # Shift WITHIN each FILE_ID group
  word_tones['PREV_WORD_TONE'] = word_tones.groupby('FILE_ID')['WORD_TONE_CAT'].shift(1)
  word_tones['NEXT_WORD_TONE'] = word_tones.groupby('FILE_ID')['WORD_TONE_CAT'].shift(-1)

  # Apply the special logic for when PREV/NEXT word has N tone
  # Need to get prev/next word syllable counts for this
  word_tones['PREV_NUM_SYLLS'] = word_tones.groupby('FILE_ID')['NUM_OF_SYLLS_IN_WORD'].shift(1)
  word_tones['NEXT_NUM_SYLLS'] = word_tones.groupby('FILE_ID')['NUM_OF_SYLLS_IN_WORD'].shift(-1)

  if full == True:
    # Override PREV_TONE: if previous word had all N's, recode based on syllable count
    word_tones.loc[word_tones['PREV_WORD_TONE'] == 'N', 'PREV_WORD_TONE'] = word_tones.loc[
        word_tones['PREV_WORD_TONE'] == 'N'
    ].apply(lambda row: 'H' if row['PREV_NUM_SYLLS'] > 1 else 'N', axis=1)



    # Override NEXT_TONE: if next word had all N's, use L for multi-syllable, N for single
    word_tones.loc[word_tones['NEXT_WORD_TONE'] == 'N', 'NEXT_WORD_TONE'] = word_tones.loc[
        word_tones['NEXT_WORD_TONE'] == 'N'
    ].apply(lambda row: 'L' if row['NEXT_NUM_SYLLS'] > 1 else 'N', axis=1)

  # Merge back to original dataframe
  df = df.drop(columns=['PREV_WORD_TONE', 'NEXT_WORD_TONE'], errors='ignore')
  df = df.merge(
      word_tones[['FILE_ID', 'WORD_START', 'WORD_END', 'PREV_WORD_TONE', 'NEXT_WORD_TONE']],
      on=['FILE_ID', 'WORD_START', 'WORD_END'],
      how='left'
  )

  # Handle PAU cases
  df.loc[df['PREV_WORD_ID'] == 'PAU', 'PREV_WORD_TONE'] = 'PAU'
  df.loc[df['NEXT_WORD_ID'] == 'PAU', 'NEXT_WORD_TONE'] = 'PAU'

  return df

